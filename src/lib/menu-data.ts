// Group items by category for each page
export function getCategoriesByPage(page: 'specials' | 'biriyani' | 'mains' | 'rice-noodles'): MenuCategory[] {
  const pageItems = MENU_ITEMS.filter((item) => item.page === page);
  const categoriesInPage = Array.from(new Set(pageItems.map((item) => item.category)));

  return categoriesInPage.map((catName) => {
    return {
      id: catName.toLowerCase().replace(/[^a-z0-9]/g, '-'),
      title: catName,
      page,
      items: pageItems.filter((i) => i.category === catName),
    };
  });
}
