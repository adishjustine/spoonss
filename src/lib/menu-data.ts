// Helper to determine dietary type
function detectDiet(name: string, category: string): MenuItem['diet'] {
  const lower = (name + ' ' + category).toLowerCase();
  if (lower.includes('fish') || lower.includes('prawn') || lower.includes('crab') || lower.includes('squid') || lower.includes('anchovy') || lower.includes('netholy') || lower.includes('thala')) {
    return 'seafood';
  }
  if (lower.includes('beef') || lower.includes('chicken') || lower.includes('non veg') || lower.includes('non-veg') || lower.includes('65') || lower.includes('al faham') || lower.includes('meat')) {
    return 'non-veg';
  }
  if (lower.includes('egg') || lower.includes('omelette') || lower.includes('boil') || lower.includes('burji')) {
    return 'egg';
  }
  return 'veg';
}

